const TABLE: Record<Lang, Record<Key, string>> = { en: EN, hi: HI };

function stored(): Lang {
  try {
    const v = localStorage.getItem(KEY);
    if (v === 'en' || v === 'hi') return v;
  } catch { /* storage blocked */ }
  return 'en';
}

export let lang: Lang = stored();
const listeners: (() => void)[] = [];
document.documentElement.lang = lang;

export function t(key: Key, vars?: Record<string, string | number>): string {
  let s = TABLE[lang][key] ?? EN[key] ?? key;
  if (vars) for (const [k, v] of Object.entries(vars)) s = s.split(`{${k}}`).join(String(v));
  return s;
}

/** t() for a key built at runtime (stage titles and the like); the key itself if there is no such line */
export function tk(key: string, vars?: Record<string, string | number>): string {
  return key in EN ? t(key as Key, vars) : key;
}

export function setLang(l: Lang): void {
  if (l === lang) return;
  lang = l;
  document.documentElement.lang = l;
  try { localStorage.setItem(KEY, l); } catch { /* not kept */ }
  for (const f of listeners) f();
}

export function onLang(f: () => void): void {
  listeners.push(f);
}

/** a number in the language's style */
export const fmtNum = (n: number) => n.toLocaleString(lang === 'hi' ? 'hi-IN' : 'en-IN');
